// Small enough to synthesize quickly; the test programs are ~17 instructions.
const int MEM_SIZE = 1024;

// Memory-mapped stream ports (see note 2 above). All are >= MEM_SIZE, so a
// normal load/store can never reach them. Keep in sync with rvasm.py.
const int MMIO_IN = 0x8000;     // load  -> int32 in
const int MMIO_OUT = 0x8004;    // store -> int32 out
const int MMIO_IN17 = 0x8008;   // load  -> ap_uint<17> in  (EVA systolic word)
const int MMIO_OUT17 = 0x800C;  // store -> ap_uint<17> out
const int MMIO_OUT26 = 0x8010;  // store -> ap_uint<26> out (EVA router packet)
const int MMIO_OUT26B = 0x8014; // store -> second packet stream (west lane 1)

// EVA's systolic word: bit0 = valid, bits[1:17] = raw fp16. Allo emits
// Stream[UInt(17), D] as hls::stream< ap_uint<17> >, so the port must say
// exactly that.
typedef ap_uint<17> sys_word_t;

// EVA's router packet: {rq,id,mode,addr,data}. Allo emits Stream[UInt(26), D]
// as hls::stream< ap_uint<26> >.
typedef ap_uint<26> pkt_t;

