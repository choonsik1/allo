/*
 * rv_stream_ip -- an RV32I soft processor exposed to Allo as an hls::stream IP.
 *
 * Derived from anjn/vhls-riscv (https://github.com/anjn/vhls-riscv), file
 * kernel.cpp, which is itself a Vitis HLS port of the core from
 * chadyuu/riscv-chisel-book. The decode/execute/writeback logic below is
 * unmodified. Four changes turn it into something Allo can wire into a
 * dataflow region:
 *
 *   1. Interface. The original top took an ap_uint<8> memory array plus an
 *      ap_uint<32>* result pointer -- a memory-mapped processor, which is what
 *      every off-the-shelf HLS soft core looks like. Allo's IPModule needs
 *      hls::stream<T> ports to splice the IP into a dataflow graph, so the top
 *      now takes two hls::stream<int32_t> references instead; see the
 *      definition below.
 *
 *      NB: do not write the top's signature out in this comment. IPModule finds
 *      the function with the regex `(\w+)\s+<top>\s*\((.*?)\)\s*[{;]` over the
 *      whole file, so a `void <top>(...)` inside a comment matches first, and
 *      the non-greedy body then runs on to the real definition's `) {` --
 *      handing the parser several hundred lines as the parameter list.
 *
 *   2. Memory-mapped stream I/O. A load from MMIO_IN becomes sin.read(); a
 *      store to MMIO_OUT becomes sout.write(). Both addresses sit above
 *      MEM_SIZE, so they cannot alias real memory -- the core tests the address
 *      before touching local_mem. This is the standard way a CPU talks to a
 *      FIFO, and it means the *program* decides when to stream, not the wrapper.
 *
 *   3. Program in ROM. The original loaded a program through the mem[] port.
 *      A stream-only interface has no such port, so the program is a static
 *      array (generated by rvasm.py) copied into local_mem at reset.
 *
 *   4. Halt. The original break condition was `pc_reg == 0x44`, hardcoded for
 *      the riscv-tests convention. It is now HALT_PC, matching the program.
 *
 * Element type is int32_t, not ap_uint<32>, to match Allo's Stream[int32, D]:
 * the emitted declaration adopts Allo's stream type, so the C++ port type has
 * to agree with it.
 */
